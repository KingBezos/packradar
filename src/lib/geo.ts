/** Best-effort IANA timezone for a US location (state + longitude for split states). */
export function timezoneFor(state: string, lat: number, lng: number): string {
  const s = state.toUpperCase();
  // Split states, approximated by longitude.
  if (s === "TN" && lng > -85.6) return "America/New_York";
  if (s === "KY" && lng < -86.0) return "America/Chicago";
  if (s === "FL" && lng < -85.0) return "America/Chicago";
  if (s === "IN" && (lng < -86.9 && (lat < 38.4 || lat > 41.0))) return "America/Chicago";
  if (s === "MI" && lng < -87.6) return "America/Menominee";
  if (s === "TX" && lng < -104.9) return "America/Denver";
  if (s === "ID" && lat > 45.5) return "America/Los_Angeles";
  if (s === "OR" && lng > -117.7 && lat < 44.5) return "America/Boise";
  if ((s === "ND" || s === "SD") && lng < -101.0) return "America/Denver";
  if ((s === "NE" || s === "KS") && lng < -101.5) return "America/Denver";
  return STATE_TZ[s] ?? "America/New_York";
}

export function slugify(s: string): string {
  return s
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 90);
}

