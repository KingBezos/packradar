import { eq } from "drizzle-orm";
import { z } from "zod";
import { route, json } from "@/lib/api";
import { requireRole } from "@/lib/session";
import { getDb } from "@/db";
import { dropCandidates, machines, newsPosts, products, retailListings, sponsors, user } from "@/db/schema";
import { slugify } from "@/lib/geo";
import { recomputeMachine } from "@/lib/drops/engine";

/**
 * Admin actions (single endpoint, discriminated by `action`):
 *  sponsor.create | sponsor.toggle | listing.create | product.create |
 *  user.role | machine.status | news.create | seed.purge
 */
const Body = z.discriminatedUnion("action", [
  z.object({
    action: z.literal("sponsor.create"),
    name: z.string().min(2),
    kind: z.enum(["local_vendor", "affiliate", "ad"]),
    tagline: z.string().optional(),
    url: z.string().min(1),
    imageUrl: z.string().optional(),
    lat: z.number().optional(),
    lng: z.number().optional(),
    radiusMiles: z.number().optional(),
    city: z.string().optional(),
    state: z.string().optional(),
    placement: z.string().default("any"),
    priority: z.number().int().default(0),
  }),
  z.object({ action: z.literal("sponsor.toggle"), id: z.string(), active: z.boolean() }),
  z.object({
    action: z.literal("product.create"),
    name: z.string().min(2),
    setName: z.string().optional(),
    category: z.string().default("other"),
    msrp: z.number().optional(),
    imageUrl: z.string().optional(),
  }),
  z.object({
    action: z.literal("listing.create"),
    productId: z.string(),
    retailer: z.string(),
    url: z.string().url(),
    affiliateUrl: z.string().url().optional(),
  }),
  z.object({ action: z.literal("user.role"), userId: z.string(), role: z.enum(["user", "mod", "admin"]) }),
  z.object({ action: z.literal("machine.status"), machineId: z.string(), status: z.enum(["active", "removed", "broken", "unverified"]) }),
  z.object({
    action: z.literal("news.create"),
    title: z.string().min(4),
    summary: z.string().min(10),
    body: z.string().optional(),
    category: z.string().default("general"),
    pinned: z.boolean().default(false),
  }),
  z.object({ action: z.literal("seed.purge") }),
]);

export const POST = route(async (req) => {
  const admin = await requireRole(["admin"]);
  const b = Body.parse(await json(req));
  const db = await getDb();
  switch (b.action) {
    case "sponsor.create": {
      const { action: _a, ...v } = b;
      await db.insert(sponsors).values(v);
      break;
    }
    case "sponsor.toggle":
      await db.update(sponsors).set({ active: b.active }).where(eq(sponsors.id, b.id));
      break;
    case "product.create": {
      const { action: _a, ...v } = b;
      await db.insert(products).values(v);
      break;
    }
    case "listing.create":
      await db.insert(retailListings).values({ productId: b.productId, retailer: b.retailer, url: b.url, affiliateUrl: b.affiliateUrl ?? null });
      break;
    case "user.role":
      await db.update(user).set({ role: b.role }).where(eq(user.id, b.userId));
      break;
    case "machine.status":
      await db.update(machines).set({ status: b.status }).where(eq(machines.id, b.machineId));
      break;
    case "news.create":
      await db.insert(newsPosts).values({
        slug: `${slugify(b.title)}-${Date.now().toString(36)}`,
        title: b.title,
        summary: b.summary,
        body: b.body ?? null,
        category: b.category,
        pinned: b.pinned,
        author: admin.name,
        autoGenerated: false,
        sourceName: "PackRadar",
      });
      break;
    case "seed.purge": {
      // Remove demo schedules before launch.
      const seeded = await db.delete(dropCandidates).where(eq(dropCandidates.source, "seed")).returning({ machineId: dropCandidates.machineId });
      for (const id of new Set(seeded.map((s) => s.machineId))) await recomputeMachine(db, id, "demo data removed");
      return { ok: true, removed: seeded.length };
    }
  }
  return { ok: true };
});
